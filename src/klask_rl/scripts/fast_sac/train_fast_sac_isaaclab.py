@dataclass
class PoolEntry:
    """Opponent pool entry with win-rate tracking."""

    state_dict: dict[str, torch.Tensor]
    birth_step: int
    wins: int = 0
    losses: int = 0
    draws: int = 0
    protected: bool = False


def pool_win_rate(entry: PoolEntry) -> float:
    """Win rate against this opponent (default 0.5 if < 10 games played)."""
    total = entry.wins + entry.losses + entry.draws
    return entry.wins / total if total >= 10 else 0.5


