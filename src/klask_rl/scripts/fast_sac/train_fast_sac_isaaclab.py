def update_critic(
    data,
    actor,
    qnet,
    qnet_target,
    q_optimizer,
    alpha_optimizer,
    log_alpha,
    target_entropy,
    scaler,
    config,
    device,
    amp_dtype,
):
    """Distributional critic update + entropy autotune."""
    with autocast(device_type="cuda", dtype=amp_dtype, enabled=config.amp):
        next_observations = data["next"]["observations"]
        critic_observations = data["critic_observations"]
        next_critic_observations = data["next"]["critic_observations"]
        actions = data["actions"]
        rewards = data["next"]["rewards"]
        dones = data["next"]["dones"].bool()
        truncations = data["next"]["truncations"].bool()
        bootstrap = (truncations | ~dones).float()

        with torch.no_grad():
            next_actions, next_log_probs = actor.get_actions_and_log_probs(next_observations)
            discount = config.gamma ** data["next"]["effective_n_steps"]
            target_distributions = qnet_target.projection(
                next_critic_observations,
                next_actions,
                rewards - discount * bootstrap * log_alpha.exp() * next_log_probs,
                bootstrap,
                discount,
            )

        q_outputs = qnet(critic_observations, actions)
        critic_log_probs = F.log_softmax(q_outputs, dim=-1)
        critic_losses = -torch.sum(target_distributions * critic_log_probs, dim=-1)
        qf_loss = critic_losses.mean(dim=1).sum(dim=0)

    q_optimizer.zero_grad(set_to_none=True)
    scaler.scale(qf_loss).backward()
    scaler.unscale_(q_optimizer)
    scaler.step(q_optimizer)
    scaler.update()

    alpha_loss = torch.tensor(0.0, device=device)
    if config.use_autotune:
        alpha_optimizer.zero_grad(set_to_none=True)
        with autocast(device_type="cuda", dtype=amp_dtype, enabled=config.amp):
            alpha_loss = (-log_alpha.exp() * (next_log_probs.detach() + target_entropy)).mean()
        scaler.scale(alpha_loss).backward()
        scaler.unscale_(alpha_optimizer)
        scaler.step(alpha_optimizer)
        scaler.update()

    return qf_loss.detach(), alpha_loss.detach(), rewards.mean().detach()


def update_actor(data, actor, qnet, actor_optimizer, log_alpha, scaler, config, amp_dtype):
    """Actor update: maximize Q - alpha * log_prob."""
    with autocast(device_type="cuda", dtype=amp_dtype, enabled=config.amp):
        critic_observations = data["critic_observations"]
        actions, log_probs = actor.get_actions_and_log_probs(data["observations"])
        q_outputs = qnet(critic_observations, actions)
        q_probs = F.softmax(q_outputs, dim=-1)
        q_values = qnet.get_value(q_probs)
        qf_value = q_values.mean(dim=0)
        actor_loss = (log_alpha.exp().detach() * log_probs - qf_value).mean()

    actor_optimizer.zero_grad(set_to_none=True)
    scaler.scale(actor_loss).backward()
    scaler.unscale_(actor_optimizer)
    scaler.step(actor_optimizer)
    scaler.update()
    return actor_loss.detach()


_NOW_PATTERN = re.compile(r"\$\{now:([^}]*)\}")


def resolve_now_placeholders(template: str, now: datetime | None = None) -> str:
    """Expand Hydra-style ``${now:FMT}`` placeholders using ``datetime.strftime``."""
    now = now or datetime.now()
    return _NOW_PATTERN.sub(lambda m: now.strftime(m.group(1)), template)


